// node --test tests/letter-drafts.ui.mjs (Chrome или CHROME_PATH); Worker и D1 из локального тестового мира.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { startWorld, restoreFetch } from './support/world.mjs';
import { initData } from './support/auth.mjs';

test('041: редактор на телефоне, закрытие при вводе и переключение режима', async (t) => {
  const browser = await chromium.launch(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : { channel: 'chrome' });
  t.after(() => browser.close());
  const w = await startWorld();
  t.after(restoreFetch);
  const owner = { id: 101, name: 'Олег' };
  await w.say(owner, '/start ' + (await w.setup()).adminCode);
  await w.say(owner, owner.name);
  const event = (await w.api(owner, 'admin.events.create', { title: 'Семья' })).event.id;
  await w.api(owner, 'admin.participate', { event, on: true });
  const page = await browser.newPage({ viewport: { width: 390, height: 640 }, isMobile: true, hasTouch: true });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', async (route) => {
    const req = route.request(), url = new URL(req.url());
    if (url.host !== 'w.test') return route.abort();
    const res = await w.request(url.pathname, { method: req.method(), headers: req.headers(), body: req.postData() });
    await route.fulfill({ status: res.status, headers: Object.fromEntries(res.headers), body: await res.text() });
  });
  await page.goto('https://w.test/app?event=' + event + '#tgWebAppData=' + encodeURIComponent(initData(owner)));
  const btn = name => page.getByRole('button', { name, exact: true });
  const management = page.getByRole('button', { name: /🛠 Управление/ });
  const setFlag = async (enabled) => {
    await management.click();
    await page.getByLabel('Черновики писем').setChecked(enabled);
    const saved = page.waitForResponse(r => r.url().endsWith('/api/event.get'));
    await btn('Сохранить').click();
    await saved;
    await page.getByRole('button', { name: /✉️ Письмо/ }).click();
  };
  await btn('Сохранить').waitFor();
  assert.equal(await page.getByRole('status').count(), 0);
  await page.setViewportSize({ width: 320, height: 640 });
  await page.getByRole('button', { name: /ℹ️ Инфо/ }).click();
  const info = page.locator('.ds-info-grid');
  assert.equal(await info.getByText('Владелец', { exact: true }).locator('xpath=following-sibling::dd[1]').textContent(), owner.name);
  assert.equal(await info.getByText('Администраторы', { exact: true }).count(), 0);
  assert.ok(await management.locator('.ds-tab__label').evaluate((label) => label.scrollWidth <= label.clientWidth));
  await page.setViewportSize({ width: 390, height: 640 });
  await setFlag(true);
  const field = page.getByLabel('Текст письма'), status = page.getByRole('status');
  await field.fill('Хочу чай');
  await page.reload();
  await field.waitFor();
  assert.equal(await field.inputValue(), 'Хочу чай');
  await btn('Опубликовать письмо').click();
  await status.getByText('✅ Опубликовано', { exact: true }).waitFor();
  const long = 'Строчка письма\n'.repeat(75);
  const saved = page.waitForResponse(r => r.url().endsWith('/api/wishlist.draft'));
  await field.fill(long);
  await saved;
  await page.evaluate(() => window.scrollTo(0, 460));
  const box = await status.boundingBox();
  assert.ok(box.y >= 0 && box.y + box.height <= 640);
  await btn('Посмотреть опубликованное').click();
  await page.getByText('Хочу чай', { exact: true }).waitFor();
  await page.getByTitle('Закрыть', { exact: true }).click();
  await setFlag(false);
  const legacy = page.locator('textarea.ds-input--letter');
  assert.equal(await legacy.inputValue(), 'Хочу чай');
  await legacy.fill('Теперь кофе');
  await btn('Сохранить').click();
  await page.getByText(/^Сохранено сегодня в /).waitFor();
  await setFlag(true);
  assert.equal(await field.inputValue(), 'Теперь кофе');
  await btn('Восстановить прежний черновик').click();
  assert.equal(await field.inputValue(), long);
  await status.getByText('📝 Черновик изменений').waitFor();
  // Ошибка автосохранения оставляет введённый текст и прежнюю публикацию.
  await page.route('**/api/wishlist.draft', route => route.abort(), { times: 1 });
  await field.fill('Идея без связи');
  await status.getByText(/Черновик не сохранён/).waitFor();
  const retried = page.waitForResponse(r => r.url().endsWith('/api/wishlist.draft') && r.ok());
  await btn('Повторить сохранение').click();
  await retried;
  const member = (await w.api(owner, 'event.get', { event })).member;
  assert.equal(member.draft.text, 'Идея без связи');
  assert.equal(member.wishlist, 'Теперь кофе');
  assert.deepEqual(errors, []);
});
